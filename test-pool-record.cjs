const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname,'pool-record.js'),'utf8'),sandbox);
const adapter=sandbox.window.ManualPoolRecord,cards=[{id:'spell'},{id:'land'}];
const old={pool:{spell:2},deck:{spell:1},basics:{land:8},notes:'Conservare le note',extra:{untouched:true}};
assert.equal(adapter.validate(old,cards),old);
const next=adapter.withPool(old,{spell:3});
assert.equal(next.deck.spell,1);assert.equal(next.basics.land,8);assert.equal(next.notes,old.notes);assert.equal(next.extra,old.extra);
assert.equal(old.pool.spell,2,'Reading and adapting a record must not mutate the original.');
assert.equal(adapter.withPool(old,{}).deck.spell,undefined,'Removing copies must keep deck counts consistent.');
for(const bad of [{...old,deck:{spell:3}},{...old,pool:{foreign:1}},{...old,basics:[]},{...old,version:99},{...old,pool:{spell:-1}}])assert.throws(()=>adapter.validate(bad,cards));
assert.equal(adapter.validate({...old,pool:{spell:999}},cards).pool.spell,999);
const identities=[{id:'original',name:'Shock'},{id:'bonus',name:'Shock'}],duplicate={pool:{original:2,bonus:3},deck:{bonus:2},basics:{},notes:'Two products'};
const unchanged=adapter.withNamedPool(duplicate,{Shock:5},identities);
assert.equal(JSON.stringify(unchanged),JSON.stringify(duplicate),'Editing notes must not collapse distinct existing IDs.');
const increased=adapter.withNamedPool(duplicate,{Shock:6},identities);
assert.equal(increased.pool.original,3);assert.equal(increased.pool.bonus,3);assert.equal(increased.deck.bonus,2);
const reduced=adapter.withNamedPool({...duplicate,deck:{bonus:3}},{Shock:4},identities);
assert.equal(reduced.pool.original,1);assert.equal(reduced.pool.bonus,3);assert.equal(reduced.deck.bonus,3,'Remove sideboard copies before changing the deck.');
assert.equal(adapter.validate({...old,pool:{spell:2,land:0}},cards).pool.land,0);
console.log('PASS: manual pool IDs, deck, basics, notes and extensions preserved; invalid records rejected without mutation.');
