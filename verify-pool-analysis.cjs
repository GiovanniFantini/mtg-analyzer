'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const A=require('./draft-advisor.js');
const cards=JSON.parse(fs.readFileSync('expansions/reality-fracture/cards.json','utf8')).cards;
const get=n=>{const c=cards.find(c=>c.name===n);assert(c,n);return c;};
const analyze=(pool,plan)=>A.poolAnalysis(A.context(cards,pool,plan),pool);
const lifegain={"Unflinching Hortimancer":2,"Break Under Pressure":2,"Surgical Precision":1,"Eye of Jace":1};
let a=analyze(lifegain,'WB');
const life=a.observations.find(o=>o.title==='Vite che sviluppano il campo');
assert(life);assert.equal(life.targets[0].quantity,2);
assert(life.sources.some(e=>e.card.name==='Break Under Pressure'));
assert(a.observations.find(o=>o.title==='Interagire e guadagnare tempo').sources.some(e=>e.card.name==='Surgical Precision'));
assert(!A.profile({oracle:'Whenever you gain life, draw a card.'}).life,'A payoff is not a lifegain source');
assert(!A.profile({oracle:'Choose one —\n• Destroy target creature.\n• You gain 3 life.'}).lifeInteraction,'Separate modes cannot remove and gain life together');
assert(!A.profile({oracle:'(Put a loyalty counter on a Jace token with "[−1]: Surveil 1".)'}).selection,'Reminder text is not an automatic surveil effect');
a=analyze({'Eye of Jace':1,'Prudent Fateseer':1,'Desperate Futurescribe':1},'WU');
assert.equal(a.observations.find(o=>o.title==='Selezione con un beneficio aggiuntivo').targets.length,2);
a=analyze({'Way of the Pyromancer':1,'Kiora of Salt and Sand':2},'URG');
assert(a.observations.some(o=>o.title==='Dalle abilità di lealtà agli attacchi'));
const finalPool={'Kiora of Salt and Sand':2,'Craftwork Crusher':1,'Undulating Witness':2,'Semester Foreseer':1,'Tam\'s Resistance':1};
a=analyze(finalPool,'UR');
assert.equal(a.outside.length,2);assert.equal(a.fixing[0].quantity,2);
assert.equal(a.outside.find(e=>e.card.name==='Craftwork Crusher').symbols,'{G}{G}');
assert(a.outside.find(e=>e.card.name==='Craftwork Crusher').repeated);
assert(!a.outside.find(e=>e.card.name==='Kiora of Salt and Sand').repeated);
assert(!a.outside.some(e=>e.card.name==="Tam's Resistance"),'Hybrid can be paid in the main colors');
assert.equal(a.resources.prepared,1);assert.equal(a.resources.tokens,1,'Prepared spell is future token production');
assert(A.profile(get('Murmuring Volume')).fixing);assert(A.profile(get('Loot, the Nexus')).fixing);
assert(!A.profile({oracle:'Discard a card: Draw a card.'}).fixing,'Filtering is not fixing');
a=analyze({'Eye of Jace':1,'Unflinching Hortimancer':2},'UR');
assert.equal(a.observations.length,0,'Do not describe synergies with an off-plan payoff as established');
assert.equal(analyze({'Eye of Jace':1},'U').observations.length,0);
assert.equal(A.poolAnalysis(A.context([{id:'unknown',name:'unknown',cost:'{U}'}],{unknown:2},'U'),{unknown:2}).missing,2);
console.log('Pool analysis: lifegain, modes, timing, resources, hybrid mana, fixing and missing data verified.');
